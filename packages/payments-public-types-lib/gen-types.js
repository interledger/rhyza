const { execSync } = require('child_process');
const { mkdirSync, rmSync } = require('fs');
const { join } = require('path');
const path = require('path');
const { copyFileSync, cpSync } = require('node:fs');
const fs = require('node:fs');

const SRC_DIR = path.resolve(__dirname, 'src');
const DIST_DIR = path.resolve(__dirname, 'dist');

const SRC_PROTO_DIR = path.resolve(SRC_DIR, 'proto_files');
const DIST_PROTO_DIR = path.resolve(DIST_DIR, 'proto_files');

const SRC_GENERATED_DIR = path.resolve(SRC_DIR, 'proto_generated');
const DIST_GENERATED_DIR = path.resolve(DIST_DIR, 'proto_generated');

try {
  rmSync(join(DIST_DIR), { recursive: true, force: true });
  rmSync(join(SRC_GENERATED_DIR), { recursive: true, force: true });
} catch (err) {
  console.error('Error while cleaning the output directory:', err);
}

// make sure generated directories exist
mkdirSync(SRC_GENERATED_DIR, { recursive: true });
mkdirSync(DIST_GENERATED_DIR, { recursive: true });

// Generate JavaScript code to the dist directory
try {
  execSync(
    `pnpm exec grpc_tools_node_protoc \
    --plugin=protoc-gen-grpc=$(pnpm bin)/grpc_tools_node_protoc_plugin \
    --js_out=import_style=commonjs,binary:${DIST_GENERATED_DIR} \
    --grpc_out=grpc_js:${DIST_GENERATED_DIR} \
    -I ${SRC_PROTO_DIR} \
    ${SRC_PROTO_DIR}/*.proto`,
    { stdio: 'inherit' }
  );
} catch (err) {
  console.error('Error while generating JavaScript code:', err);
}

// Generate TypeScript code (d.ts) to the src directory
try {
  execSync(
    `pnpm exec grpc_tools_node_protoc \
    --plugin=protoc-gen-grpc=$(pnpm bin)/grpc_tools_node_protoc_plugin \
    --ts_out=grpc_js:${SRC_GENERATED_DIR} \
    -I ${SRC_PROTO_DIR} \
    ${SRC_PROTO_DIR}/*.proto`,
    { stdio: 'inherit' }
  );
} catch (err) {
  console.error('Error while generating TypeScript code:', err);
}

// generate index.ts to re-export all .d.ts files created in the src/proto_generated
const files = fs
  .readdirSync(SRC_GENERATED_DIR)
  .filter((file) => file.endsWith('.d.ts'));

let exportHeader = `/*\nThis file is automatically generated by ${path.basename(__filename)}, don't directly change it\n*/`;
exportHeader += '\n"use strict";\n\n';
const exportStatements =
  files
    .map((file) => {
      const moduleName = path.basename(file, '.d.ts');
      return `export * from "./${moduleName}";`;
    })
    .join('\n') + '\n';
// Write the index.ts file
fs.writeFileSync(
  path.join(SRC_GENERATED_DIR, 'index.ts'),
  exportHeader + exportStatements
);

// Copy proto and generated files to dist
try {
  cpSync(SRC_PROTO_DIR, DIST_PROTO_DIR, { recursive: true });
  cpSync(SRC_GENERATED_DIR, DIST_GENERATED_DIR, { recursive: true });
} catch (err) {
  console.error('Error while copying generated files to dist:', err);
}
